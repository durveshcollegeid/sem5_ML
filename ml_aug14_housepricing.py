"""Perform ordinal encoding on eligible categorical columns ( **paused** )

Perform one hot encoding on remaining categorical columns
"""

available_cols = X.columns

for col in available_cols :
  temp_col = X[col]
  if ( temp_col.dtype == 'object' ) :
    X = pd.get_dummies( temp_col )

"""Typecast the Boolean values of OHE into integers

"""

for col in X.columns :
  temp_col = X[col]
  if ( temp_col.dtype == 'bool' ) :
    temp_col = temp_col.astype( int )
    X[col] = temp_col

"""
Split test_train"""

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split( X, y, test_size = 0.2 )

"""

Import linear regression
"""

from sklearn.linear_model import LinearRegression

model = LinearRegression()

"""
Fit linear regression
"""

model.fit( X_train, y_train )

"""
Predict values using the model
"""

y_pred = model.predict( X_test )

