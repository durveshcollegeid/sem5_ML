"""Fill the null values with mean for numeric columns

"""

cols_with_less_samples = {}

for col in X.columns :
  temp_col = X[col]
  temp_len = len( temp_col.dropna() )
  #print( len(temp_col) )
  if ( temp_len < len_of_X ) :
    #print( f"len of {col} is {len(col)}" )
    cols_with_less_samples[col] = temp_len

print( cols_with_less_samples )

for col in cols_with_less_samples :
  if ( X[col].dtype == 'int64' or X[col].dtype == 'float64' ) :
    temp_col = X[col]
    temp_mean_value = temp_col.mean()
    X[col] = temp_col.fillna(  temp_mean_value )

X.info()

X.describe()

"""Perform Standardization on numeric columns"""

from sklearn.preprocessing import StandardScaler

scaler_instance = StandardScaler()

for col in X.columns :
  temp_col = X[col]
  if ( temp_col.dtype == 'int64' or temp_col.dtype == 'float64' ) :
    temp_col = temp_col.values.reshape( -1,1 )
    temp_col = scaler_instance.fit_transform( temp_col )
    X[col] = temp_col

"""Remove outliers from the newly obtained columns

"""

for col in X.columns :
  temp_col = X[col]
  if ( temp_col.dtype == 'int64' or temp_col.dtype == 'float64' ) :
    q1 = temp_col.quantile( 0.25 )
    q2 = temp_col.quantile( 0.5 )
    q3 = temp_col.quantile( 0.75 )
    iqr = q3 - q2
    LL = q2 - 1.5*iqr
    UL = q3 + 1.5*iqr
    temp_col = temp_col[ (temp_col > LL) & (temp_col < UL) ]
    X[col] = temp_col

X.info()

X.describe()

"""Drop the columns with zero eligible values"""

for col in X :
  temp_col = X[col]
  if ( temp_col.dtype == 'int64' or temp_col.dtype == 'float64' ) :
    if( ( len(temp_col) - temp_col.isnull().sum()) == 0  ) :
      X = X.drop( col, axis = 1 )

X.info()

"""Drop the columns with very few not-null values after removing outliers"""

cols_with_less_samples = {}

for col in X.columns :
  temp_col = X[col]
  temp_len = len( temp_col.dropna() )
  #print( len(temp_col) )
  if ( temp_len < len_of_X ) :
    #print( f"len of {col} is {len(col)}" )
    cols_with_less_samples[col] = temp_len

print( cols_with_less_samples )

#assume 80% margin for filling null values, drop others

