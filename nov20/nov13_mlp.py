import numpy as np
from sklearn.neural_network import MLPClassifier
from sklearn.linear_model import Perceptron
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split

xor = np.array( [ [0,0],[0,1],[1,0],[1,1] ] )

y = np.array( [0,1,1,0] )

model_p = Perceptron( max_iter=1000, random_state=42 )
model_p.fit( xor, y )

print( "Perceptron predictions : ", model_p.predict( xor ) )
print( "Perceptron accuracy : ", accuracy_score( y, model_p.predict( xor ) ) )

model_mlp = MLPClassifier( hidden_layer_sizes=(4,),
activation = "tanh", solver="lbfgs", max_iter=5000, random_state=42
                           )

model_mlp.fit( xor, y )

print( "MLP predictions : ", model_mlp.predict( xor ) )
print( "MLP accuracy : ", accuracy_score( y, model_mlp.predict( xor ) ) )

