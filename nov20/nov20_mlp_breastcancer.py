"""# make function for creating variants"""

model_dict = { "name" : [], "accuracy_score" : [] }

def update_model_dict( model_name, model_acc ) :
  model_dict["name"].append( model_name )
  model_dict["accuracy_score"].append( model_acc )

def model_pipeline( iter_value, activation_func, tuple_value ) :
  model = MLPClassifier( hidden_layer_sizes=tuple(tuple_value), max_iter=int(iter_value), activation = str(activation_func) )
  model.fit( X_train, y_train )
  pred = model.predict( X_test )
  acc = accuracy_score( y_true = y_test, y_pred = pred )
  update_model_dict( model_name = f"{activation_func}_{iter_value}", model_acc = acc )

def funnel_like_tuple( layers_num ) :
  layers_num = int( layers_num )

  result = [2]
  if( layers_num == 1 ) :
    return tuple(result)
  for i in range(1,layers_num) :
    result.append( 2*result[-1] )
    #print(result)
  result.reverse(  ) #modifies the original list
  result = tuple(result)
  return result

#print( funnel_like_tuple( 5 ) )

def create_tuple_list( variant_num ) :
  variant_num = int( variant_num )
  result = []
  for i in range(1,variant_num+1) :
    result.append( funnel_like_tuple( i ) )
  return result

LAYER_TUPLE = ( 16,8,4,2 )

iter_list = [100, 500, 1000, 2000]
activation_list = [ "relu", "tanh", "logistic" ]
tuple_list = create_tuple_list( 5 )

#4*3*5 = 60 variations

for activation_func in activation_list :
  for tuple_value in tuple_list :
    for iter_value in iter_list :
      model_pipeline( iter_value, activation_func, tuple_value )

